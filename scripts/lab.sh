#!/usr/bin/env bash
# Replaces the instructor's just recipes without modifying the source SQL or import options.
set -euo pipefail
ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
LAB="$ROOT/lab"
export PGHOST="${PGHOST:-localhost}"
export PGPORT="${POSTGIS_PORT:-5432}"
export PGDATABASE="${PGDATABASE:-lab1}"
export PGUSER="${PGUSER:-lab1}"
export PGPASSWORD="${POSTGIS_PASSWORD:-lab1-local-only}"
GPKG="${GPKG:-$LAB/data/niedersachsen-261028-free/niedersachsen.gpkg}"
PBF="${PBF:-$LAB/data/niedersachsen-261028.osm.pbf}"
SNAPSHOT="${SNAPSHOT:-2026-10-28}"
# Four bounding coordinates, or empty string to import all of Niedersachsen.
BBOX="${BBOX-9.60 52.30 9.92 52.45}"
SPAT=()
if [[ -n "$BBOX" ]]; then
    read -r -a coordinates <<< "$BBOX"
    if [[ ${#coordinates[@]} -ne 4 ]]; then
        echo 'BBOX must have exactly four coordinates or be empty' >&2
        exit 2
    fi
    SPAT=(-spat "${coordinates[@]}")
fi
PG_OGR="PG:host=$PGHOST port=$PGPORT dbname=$PGDATABASE user=$PGUSER"
GEOSERVER="${GEOSERVER_URL:-http://localhost:${GEOSERVER_PORT:-8081}/geoserver}"
GEOSERVER_AUTH="${GEOSERVER_ADMIN_USER:-admin}:${GEOSERVER_ADMIN_PASSWORD:-lab1-local-only}"
usage() {
    cat <<'USAGE'
Usage: scripts/lab.sh <command> [arguments]
  stack-up                 Start PostGIS and GeoServer, wait for database
  db-setup                 Create extensions and base schemas
  import-gpkg              Import Hannover GeoPackage (GPKG / BBOX overrides)
  import-addresses         Import addresses from PBF (PBF / BBOX overrides)
  search-index             Create materialized index and functions (SNAPSHOT override)
  search <q> [limit]       Smoke-test free-text search
  reverse <lon> <lat> [r]  Smoke-test reverse lookup
  geoserver-publish        Publish original GIS layers (optional)
  refresh-index            Refresh materialized view concurrently
  db                       Start interactive psql
  stack-down                Stop containers, retaining named volumes
USAGE
}
require_file() { [[ -f "$1" ]] || { printf 'Missing required input: %s\n' "$1" >&2; exit 2; }; }
command="${1:-help}"; shift || true
case "$command" in
    stack-up)
        docker compose -f "$LAB/compose.yaml" up -d
        for ((attempt=0;attempt<90;attempt++)); do
            if psql -Atc 'SELECT 1' >/dev/null 2>&1; then exit 0; fi
            sleep 2
        done
        echo 'PostGIS did not become ready after 3 minutes' >&2; exit 1 ;;
    db-setup) psql -v ON_ERROR_STOP=1 -f "$LAB/sql/02-db-setup.sql" ;;
    import-gpkg)
        require_file "$GPKG"
        ogr2ogr -f PostgreSQL "$PG_OGR" "$GPKG" -a_srs EPSG:4326 \
            -doo ACTIVE_SCHEMA=osm -lco GEOMETRY_NAME=geom -append \
            --config OGR_TRUNCATE YES -progress "${SPAT[@]}" \
            gis_osm_places_free gis_osm_pois_free gis_osm_pois_a_free \
            gis_osm_roads_free gis_osm_adminareas_a_free ;;
    import-addresses)
        require_file "$PBF"
        export OSM_CONFIG_FILE="$LAB/osmconf-addresses.ini"
        for layer in points multipolygons; do
            ogr2ogr -f PostgreSQL "$PG_OGR" "$PBF" "$layer" \
                -where 'addr_housenumber IS NOT NULL' \
                -nln "osm.address_$layer" -lco GEOMETRY_NAME=geom -append \
                --config OGR_TRUNCATE YES -progress "${SPAT[@]}"
        done ;;
    search-index)
        psql -v ON_ERROR_STOP=1 -v snapshot="$SNAPSHOT" -f "$LAB/sql/05-search-index.sql"
        psql -v ON_ERROR_STOP=1 -f "$LAB/sql/06-search-functions.sql" ;;
    search)
        [[ $# -ge 1 ]] || { usage >&2; exit 2; }
        psql -v ON_ERROR_STOP=1 -v q="$1" -v lim="${2:-10}" \
            -c "SELECT name, label, type, category, round(score::numeric, 3) AS score, round(lon::numeric, 5) AS lon, round(lat::numeric, 5) AS lat FROM search.search(:'q', :lim);" ;;
    reverse)
        [[ $# -ge 2 ]] || { usage >&2; exit 2; }
        psql -v ON_ERROR_STOP=1 -v lon="$1" -v lat="$2" -v r="${3:-250}" \
            -c 'SELECT label, type, round(distance_m::numeric, 1) AS distance_m FROM search.reverse(:lon, :lat, :r);' ;;
    geoserver-publish)
        for ws in osm search; do
            if [[ "$(curl -s -o /dev/null -w '%{http_code}' -u "$GEOSERVER_AUTH" "$GEOSERVER/rest/workspaces/$ws.json")" == 404 ]]; then
                curl -fsS -u "$GEOSERVER_AUTH" -H 'Content-Type: application/json' -X POST "$GEOSERVER/rest/workspaces" -d "{\"workspace\":{\"name\":\"$ws\"}}"
            fi
            # Use JSON generated by python, not string substitution of credentials into shell code.
            store="$(python3 - "$ws" "$PGDATABASE" "$PGUSER" "$PGPASSWORD" <<'PY'
import json,sys
ws,db,user,pw=sys.argv[1:]
entries={'dbtype':'postgis','host':'postgis','port':'5432','database':db,'user':user,'passwd':pw,'schema':ws,'Expose primary keys':'true'}
print(json.dumps({'dataStore':{'name':'lab1','type':'PostGIS','connectionParameters':{'entry':[{'@key':k,'$':v} for k,v in entries.items()]}}}))
PY
)"
            endpoint="$GEOSERVER/rest/workspaces/$ws/datastores"
            if [[ "$(curl -s -o /dev/null -w '%{http_code}' -u "$GEOSERVER_AUTH" "$endpoint/lab1.json")" == 404 ]]; then
                curl -fsS -u "$GEOSERVER_AUTH" -H 'Content-Type: application/json' -X POST "$endpoint" -d "$store"
            else
                curl -fsS -u "$GEOSERVER_AUTH" -H 'Content-Type: application/json' -X PUT "$endpoint/lab1" -d "$store"
            fi
        done
        for ft in osm:gis_osm_places_free osm:gis_osm_pois_free osm:gis_osm_roads_free osm:gis_osm_adminareas_a_free search:search_index; do
            ws="${ft%%:*}"; name="${ft#*:}"
            endpoint="$GEOSERVER/rest/workspaces/$ws/datastores/lab1/featuretypes"
            if [[ "$(curl -s -o /dev/null -w '%{http_code}' -u "$GEOSERVER_AUTH" "$endpoint/$name.json")" == 404 ]]; then
                curl -fsS -u "$GEOSERVER_AUTH" -H 'Content-Type: application/json' -X POST "$endpoint" \
                    -d "{\"featureType\":{\"name\":\"$name\",\"srs\":\"EPSG:4326\",\"projectionPolicy\":\"FORCE_DECLARED\"}}"
            fi
            echo "published $ft"
        done
        curl -fsS "$GEOSERVER/ows?service=WFS&version=2.0.0&request=GetFeature&typeNames=search:search_index&count=1&outputFormat=application/json" | head -c 400 || true
        echo ;;
    refresh-index)
        psql -v ON_ERROR_STOP=1 -c 'REFRESH MATERIALIZED VIEW CONCURRENTLY search.search_index;' \
            -c 'SELECT snapshot_id, refreshed_at, count(*) AS documents FROM search.search_index GROUP BY 1, 2;' ;;
    db) exec psql ;;
    stack-down) docker compose -f "$LAB/compose.yaml" down ;;
    help|-h|--help) usage ;;
    *) usage >&2; exit 2 ;;
esac
